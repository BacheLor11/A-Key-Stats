import Foundation

/// HID usage（键盘描述符里的用法 ID，USB HID Usage Tables 第 12 章）
/// → macOS 虚拟键码（`kVK_*`，CGEvent / NSEvent.keyCode 那一套）。
///
/// 这两套编号毫无关系：HID 的 'a' 是 0x04，而 macOS 的 'a' 是 0。之前直接
/// 把 usage 当虚拟键码用，敲 A 亮的是 H，敲空格亮的是 `/`，全错位。
/// 映射按物理位置对齐（都是 ANSI 参考位置），与输入法、键盘语种无关。
public enum HIDKeymap {
    public static func virtualKey(for usage: UInt16) -> UInt16? {
        table[usage]
    }

    /// 已识别但界面没有对应键帽的（音量、亮度这类走 0x0C 页，不在这里）
    public static func isKnown(_ usage: UInt16) -> Bool { table[usage] != nil }

    private static let table: [UInt16: UInt16] = [
        // 字母
        0x04: 0x00,  // a → A
        0x05: 0x0B,  // b → B
        0x06: 0x08,  // c → C
        0x07: 0x02,  // d → D
        0x08: 0x0E,  // e → E
        0x09: 0x03,  // f → F
        0x0A: 0x05,  // g → G
        0x0B: 0x04,  // h → H
        0x0C: 0x22,  // i → I
        0x0D: 0x26,  // j → J
        0x0E: 0x28,  // k → K
        0x0F: 0x25,  // l → L
        0x10: 0x2E,  // m → M
        0x11: 0x2D,  // n → N
        0x12: 0x1F,  // o → O
        0x13: 0x23,  // p → P
        0x14: 0x0C,  // q → Q
        0x15: 0x0F,  // r → R
        0x16: 0x01,  // s → S
        0x17: 0x11,  // t → T
        0x18: 0x20,  // u → U
        0x19: 0x09,  // v → V
        0x1A: 0x0D,  // w → W
        0x1B: 0x07,  // x → X
        0x1C: 0x10,  // y → Y
        0x1D: 0x06,  // z → Z

        // 数字行
        0x1E: 0x12,  // 1
        0x1F: 0x13,  // 2
        0x20: 0x14,  // 3
        0x21: 0x15,  // 4
        0x22: 0x17,  // 5
        0x23: 0x16,  // 6
        0x24: 0x1A,  // 7
        0x25: 0x1C,  // 8
        0x26: 0x19,  // 9
        0x27: 0x1D,  // 0
        0x2D: 0x1B,  // -
        0x2E: 0x18,  // =
        0x2F: 0x21,  // [
        0x30: 0x1E,  // ]
        0x31: 0x2A,  // backslash
        0x32: 0x2A,  // 欧版回车左侧的 #，macOS 归到 backslash
        0x33: 0x29,  // ;
        0x34: 0x27,  // '
        0x35: 0x32,  // `
        0x36: 0x2B,  // ,
        0x37: 0x2F,  // .
        0x38: 0x2C,  // /
        0x64: 0x0A,  // ISO 左下角的 § / ±

        // 控制键
        0x28: 0x24,  // return
        0x29: 0x35,  // escape
        0x2A: 0x33,  // delete（回退）
        0x2B: 0x30,  // tab
        0x2C: 0x31,  // space
        0x39: 0x39,  // caps lock

        // 修饰键（HID 左右分开报，macOS 也是）
        0xE0: 0x3B,  // 左 ctrl
        0xE1: 0x38,  // 左 shift
        0xE2: 0x3A,  // 左 opt
        0xE3: 0x37,  // 左 cmd
        0xE4: 0x3E,  // 右 ctrl
        0xE5: 0x3C,  // 右 shift
        0xE6: 0x3D,  // 右 opt
        0xE7: 0x36,  // 右 cmd

        // 功能键 F1–F12
        0x3A: 0x7A, 0x3B: 0x78, 0x3C: 0x63, 0x3D: 0x76,
        0x3E: 0x60, 0x3F: 0x61, 0x40: 0x62, 0x41: 0x64,
        0x42: 0x65, 0x43: 0x6D, 0x44: 0x67, 0x45: 0x6F,

        // 编辑与方向
        0x49: 0x72,  // insert → help
        0x4A: 0x73,  // home
        0x4B: 0x74,  // page up
        0x4C: 0x75,  // forward delete
        0x4D: 0x77,  // end
        0x4E: 0x79,  // page down
        0x4F: 0x7C,  // right
        0x50: 0x7B,  // left
        0x51: 0x7D,  // down
        0x52: 0x7E,  // up

        // 小键盘
        0x53: 0x47,  // clear
        0x54: 0x4B,  // /
        0x55: 0x43,  // *
        0x56: 0x4E,  // -
        0x57: 0x45,  // +
        0x58: 0x4C,  // enter
        0x59: 0x53,  // 1
        0x5A: 0x54,  // 2
        0x5B: 0x55,  // 3
        0x5C: 0x56,  // 4
        0x5D: 0x57,  // 5
        0x5E: 0x58,  // 6
        0x5F: 0x59,  // 7
        0x60: 0x5B,  // 8
        0x61: 0x5C,  // 9
        0x62: 0x52,  // 0
        0x63: 0x41,  // .
        0x67: 0x51,  // =

        // F13 以上
        0x68: 0x69, 0x69: 0x6B, 0x6A: 0x71, 0x6B: 0x6A,
        0x6C: 0x40, 0x6D: 0x4F, 0x6E: 0x50, 0x6F: 0x5A,

        // 日文键盘专属
        0x87: 0x5E,  // ろ / _
        0x88: 0x68,  // かな
        0x89: 0x5D,  // ¥
        0x90: 0x66,  // 英数
        0x91: 0x68,  // かな（另一路）
    ]
}
